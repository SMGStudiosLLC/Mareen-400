#!/usr/bin/env python3
"""Turn the Metal source embedded in MarennFilter.swift into C++ for the CPU harness.

Two mechanical rewrites make MSL compile as C++17 with clang:
  * vector constructor calls  float3(a, b)  ->  make_vec<float3>(a, b)
  * unsuffixed float literals  0.5          ->  0.5f   (MSL has no double)

It also reads the Swift uniform structs (GradeP, CompP, ...) and emits C++ default
initialisers from their `var name: Float = value` lines, so the harness always runs
with the exact defaults the app ships, and checks that every Swift struct matches
the MSL struct of the same name field for field.

usage: msl2cpp.py MarennFilter.swift out_dir
"""
import re
import sys
from pathlib import Path

swift_path, out_dir = Path(sys.argv[1]), Path(sys.argv[2])
swift = swift_path.read_text()

m = re.search(r'static let source = """\n(.*?)\n\s*"""', swift, re.S)
if not m:
    sys.exit("msl2cpp: embedded Metal source not found")
msl = m.group(1)

# --- MSL -> C++ ---------------------------------------------------------------
def rewrite(src: str) -> str:
    out = []
    for line in src.split("\n"):
        code, sep, comment = line.partition("//")
        code = re.sub(r"\b((?:float|half|int|uint|short|ushort|uchar)[234])\(", r"make_vec<\1>(", code)
        code = re.sub(r"(?<![\w.])(\d+\.\d*(?:[eE][+-]?\d+)?|\.\d+(?:[eE][+-]?\d+)?|\d+[eE][+-]?\d+)(?![\w.])",
                      r"\1f", code)
        out.append(code + sep + comment)
    return "\n".join(out)

cpp = rewrite(msl)
cpp = cpp.replace("#include <metal_stdlib>", '#include "metal_stdlib"')
(out_dir / "shader.inc").write_text("// generated by msl2cpp.py from MarennFilter.swift, do not edit\n" + cpp + "\n")

# --- uniform structs ------------------------------------------------------------
def swift_structs(src):
    res = {}
    for sm in re.finditer(r"\nstruct (\w+) \{(.*?)\n\}", src, re.S):
        name, body = sm.group(1), sm.group(2)
        fields = []
        for fm in re.finditer(r"var ([^:]+?): Float(?: = ([^\n]+))?", body):
            names = [n.strip() for n in fm.group(1).split(",")]
            # `var a: Float = 1.0, b: Float = 0.6` style lines
            line = fm.group(0)
            parts = re.findall(r"(\w+): Float(?: = ([-\d.eE+]+))?", line)
            for n, v in parts:
                fields.append((n, v or "0"))
        if fields:
            res[name] = fields
    return res

def msl_structs(src):
    res = {}
    for sm in re.finditer(r"struct (\w+) \{(.*?)\};", src, re.S):
        body = re.sub(r"//[^\n]*", "", sm.group(2))
        fields = []
        for decl in body.split(";"):
            decl = decl.strip()
            if not decl:
                continue
            if not decl.startswith("float "):
                fields = None
                break
            fields += [n.strip() for n in decl[len("float "):].split(",")]
        if fields:
            res[sm.group(1)] = fields
    return res

sw, ms = swift_structs(swift), msl_structs(msl)
errors = []
lines = ["// generated by msl2cpp.py from MarennFilter.swift, do not edit", "#pragma once"]
for name, fields in sw.items():
    if name not in ms:
        continue
    swift_names = [f for f, _ in fields]
    if swift_names != ms[name]:
        errors.append(f"{name}: Swift fields {swift_names} != MSL fields {ms[name]}")
    lines.append(f"inline {name} default_{name}() {{")
    lines.append(f"    {name} p;")
    for f, v in fields:
        lines.append(f"    p.{f} = {v}f;" if "." in v or "e" in v.lower() else f"    p.{f} = {v}.0f;")
    lines.append("    return p;")
    lines.append("}")
    # name lookup table for --set Struct.field=value overrides
    lines.append(f"inline float* field_{name}({name}& p, const std::string& f) {{")
    for f, _ in fields:
        lines.append(f'    if (f == "{f}") return &p.{f};')
    lines.append("    return nullptr;")
    lines.append("}")
(out_dir / "uniforms.inc").write_text("\n".join(lines) + "\n")

if errors:
    sys.exit("msl2cpp: Swift/MSL uniform layout mismatch:\n  " + "\n  ".join(errors))
print(f"msl2cpp: {len(cpp.splitlines())} lines of MSL, structs: {', '.join(n for n in sw if n in ms)}")
