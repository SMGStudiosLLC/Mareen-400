#!/usr/bin/env python3
"""Extract the embedded Metal source strings from the filter's Swift file.

The engine keeps its shader source in Swift multi-line string literals named
`prelude`, `legacySource` and `vesperSource` (older revisions used a single
`source`). This script writes each of them to `<outdir>/<name>.metal` with a
`#line` directive so C++ compiler diagnostics point back at the Swift file.

It also enforces the hygiene rules those literals must follow: no backslashes,
no triple quotes, no tabs, and no line indented less than the closing
delimiter, because Swift would either reject the file or silently change the
shader text.
"""
import re
import sys
from pathlib import Path

PATTERN = re.compile(r'^(\s*)static let (\w+) = """\s*$')


def extract(swift_path: Path):
    lines = swift_path.read_text(encoding="utf-8").split("\n")
    blocks = {}
    i = 0
    while i < len(lines):
        m = PATTERN.match(lines[i])
        if not m:
            i += 1
            continue
        name = m.group(2)
        start = i + 1
        j = start
        while j < len(lines) and lines[j].strip() != '"""':
            j += 1
        if j >= len(lines):
            raise SystemExit(f"{swift_path}: unterminated string literal {name}")
        closing_indent = len(lines[j]) - len(lines[j].lstrip())
        body = lines[start:j]
        problems = []
        for k, line in enumerate(body, start=start + 1):
            if "\\" in line:
                problems.append(f"line {k}: backslash inside Metal source")
            if '"""' in line:
                problems.append(f"line {k}: triple quote inside Metal source")
            if "\t" in line:
                problems.append(f"line {k}: tab inside Metal source")
            if line.strip() and (len(line) - len(line.lstrip())) < closing_indent:
                problems.append(f"line {k}: indented less than the closing delimiter")
        if problems:
            raise SystemExit("\n".join(f"{swift_path}: {p}" for p in problems))
        # Swift strips the closing delimiter's indentation from every line.
        stripped = [line[closing_indent:] if len(line) >= closing_indent else line for line in body]
        blocks[name] = (start + 1, "\n".join(stripped) + "\n")
        i = j + 1
    return blocks


STRUCT_RE = re.compile(r'^struct (\w+)\s*\{\s*$')
VAR_RE = re.compile(r'(\w+): Float\s*=\s*([-+0-9.eE]+)')


def swift_structs(swift_path: Path):
    """Return {struct name: [(field, default value)]} for the all-Float parameter
    structs declared at the top level of the Swift file."""
    lines = swift_path.read_text(encoding="utf-8").split("\n")
    structs = {}
    i = 0
    while i < len(lines):
        m = STRUCT_RE.match(lines[i])
        if not m:
            i += 1
            continue
        name = m.group(1)
        fields = []
        j = i + 1
        while j < len(lines) and lines[j].strip() != "}":
            for fm in VAR_RE.finditer(lines[j]):
                fields.append((fm.group(1), fm.group(2)))
            j += 1
        structs[name] = fields
        i = j + 1
    return structs


def write_defaults(swift_path: Path, blocks, outdir: Path):
    """Emit build/defaults.inc with one default<Name>() function per parameter
    struct that exists in both the Swift file and the Metal source, carrying
    the Swift default values. The C++ driver uses these so it can never drift
    from what the Swift host sends to the GPU."""
    out = ["// Generated by extract_msl.py from " + swift_path.name + ". Do not edit.", ""]
    structs = swift_structs(swift_path)
    for block_name, (_, block_text) in blocks.items():
        emitted = []
        for name, fields in structs.items():
            if not re.search(r'\bstruct ' + name + r'\b', block_text):
                continue
            emitted.append(f"inline {name} default{name}() {{")
            emitted.append(f"    {name} p;")
            for field, value in fields:
                v = value
                if re.fullmatch(r'[-+]?\d+', v):
                    v += ".0"
                emitted.append(f"    p.{field} = {v}f;")
            emitted.append("    return p;")
            emitted.append("}")
            emitted.append("")
        if emitted:
            # Each renderer binary includes one kernel block, so its defaults
            # are only visible when that block is compiled in.
            out.append(f"#ifdef MSL_HAS_{block_name}")
            out.extend(emitted)
            out.append("#endif")
            out.append("")
    (outdir / "defaults.inc").write_text("\n".join(out), encoding="utf-8")
    print(f"defaults.inc: {sum(1 for l in out if l.startswith('inline'))} structs")


def main():
    if len(sys.argv) < 3:
        print("usage: extract_msl.py <Filter.swift> <outdir>")
        sys.exit(2)
    swift_path = Path(sys.argv[1])
    outdir = Path(sys.argv[2])
    outdir.mkdir(parents=True, exist_ok=True)
    blocks = extract(swift_path)
    if not blocks:
        raise SystemExit(f"{swift_path}: no Metal source strings found")
    for name, (first_line, text) in blocks.items():
        out = outdir / f"{name}.metal"
        out.write_text(f'#line {first_line} "{swift_path.name}"\n' + text, encoding="utf-8")
        print(f"{name}: {text.count(chr(10))} lines -> {out}")
    write_defaults(swift_path, blocks, outdir)


if __name__ == "__main__":
    main()
